"""The screenshot gallery's headings follow the current navigation.

docs/screenshots.md is generated by scripts/build_gallery.py (run by
scripts/demo/recapture.sh) from scripts/screenshot_manifest.json, so a stale
heading has to be fixed in the manifest; editing the page alone is undone by
the next regeneration.
"""
import json
import pathlib

from django.test import SimpleTestCase
from django.urls import reverse

from core import navigation

ROOT = pathlib.Path(__file__).resolve().parents[2]
MANIFEST = ROOT / 'scripts' / 'screenshot_manifest.json'
GALLERY = ROOT / 'docs' / 'screenshots.md'


def _shots():
    return json.loads(MANIFEST.read_text())['screenshots']


def _admin_path(url_name):
    """'Administration → <category> → <page>' for a settings tab."""
    for section in navigation.SECTIONS:
        if section.menu != 'settings':
            continue
        for tab in section.tabs:
            if tab.url_name == url_name:
                return f'Administration → {section.label} → {tab.label}'
    raise AssertionError(f'{url_name} is not an Administration tab')


class ScreenshotManifestHeadingTests(SimpleTestCase):

    def test_no_heading_uses_the_old_settings_menu_name(self):
        stale = [s['name'] for s in _shots() if s['heading'].startswith('Settings →')]
        self.assertEqual(stale, [])

    def test_billing_settings_heading_is_the_navigation_path(self):
        shot = next(s for s in _shots() if s['name'] == 'settings-billing-light')
        self.assertEqual(shot['route'], reverse('core:settings_billing'))
        self.assertEqual(shot['heading'], _admin_path('core:settings_billing'))

    def test_generated_gallery_matches_the_manifest_headings(self):
        page = GALLERY.read_text()
        headings = [line[4:] for line in page.splitlines() if line.startswith('### ')]
        self.assertEqual(headings, [s['heading'] for s in _gallery_order()])


def _gallery_order():
    """Manifest entries in the order build_gallery.py writes them."""
    import importlib.util
    spec = importlib.util.spec_from_file_location('build_gallery', ROOT / 'scripts' / 'build_gallery.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    shots = _shots()
    return [s for key, _title, _blurb in mod.GROUPS for s in shots if s['group'] == key]
