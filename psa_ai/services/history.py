"""
The ticket's AI and automation history: one staff-only, chronological
timeline of everything AI or automation did on a ticket, and what people
decided about it.

Sources (all already recorded elsewhere; this module only reads them,
except `record_draft_decision`, which writes AIDraftDecision rows):

  AISuggestion (+ AIActionLog, AIDraftDecision)   AI reply / action / triage drafts
  AnalysisJob (+ AnalysisRun, AIDraftDecision)    "Analyze ticket" / "Compare models", incl. Rem0te jobs
  RMMRequest                                      handoffs, read-only diagnostics, fix referrals,
                                                  Rem0te action proposals
  Rem0teAlertTicket                               the ticket was opened from a Rem0te alert
  psa.routing RoutingDecision                     routing (assignment only)

Who sees what (decided for v3.17.660, documented in docs/AI_TICKET_ASSIST.md):

  * MSP technicians with live technician access (tech_access) at the
    ticket's customer. Customer users, the portal, anyone who isn't MSP
    staff and technicians assigned only to other customers get nothing —
    the template tag renders nothing and the JSON route answers 404 / 403.
  * Automation entries (RMM requests, alert tickets, routing) are shown to
    any technician on the ticket: they are not AI features and work with AI
    switched off, like the RMM and Routing panels.
  * AI entries need the technician's `view_output` capability for this
    customer and ticket (technician access), the same rule as the AI panel.
  * When AI is off — the master switch, or this customer's AI policy is
    missing or has analysis switched off — already-recorded AI entries stay
    visible to those technicians as an audit record (model, profile, prompt
    version, status, who decided what and when), but no AI-written text is
    shown. Nothing new is generated by viewing the history.

Redaction: no prompt, no evidence document, no request sent to an RMM and no
provider key is ever read here. Excerpts are the stored, already redacted
model output, passed through `evidence.redact` again and cut short.

Retention: entries older than the customer's retention window
(AIBusinessPolicy.history_retention_days, default
settings.PSA_AI_HISTORY_RETENTION_DAYS = 365, 0 = keep) are left out of the
timeline and deleted by `purge_expired()`, which the `poll_analysis_jobs`
scheduled task runs at most every PURGE_EVERY. Routing decisions and alert
→ ticket links are not deleted (they are what stops a repeated trigger or
alert from routing twice or opening a second ticket); they only drop out of
this timeline.

Nothing here calls an RMM, Rem0te or a model provider.
"""
from __future__ import annotations

import logging
from datetime import timedelta

from django.conf import settings
from django.db import transaction
from django.utils import timezone

logger = logging.getLogger('psa_ai')

DEFAULT_RETENTION_DAYS = 365
PURGE_EVERY = timedelta(hours=6)
MAX_ENTRIES = 100
EXCERPT_CHARS = 300
ROUTING_ASSURANCE = ('Routing changes assignment, queue and team only. It never started a remote session '
                     'or authorized an endpoint action.')


# --- retention -----------------------------------------------------------------

def default_retention_days() -> int:
    try:
        return max(0, int(getattr(settings, 'PSA_AI_HISTORY_RETENTION_DAYS', DEFAULT_RETENTION_DAYS)))
    except (TypeError, ValueError):
        return DEFAULT_RETENTION_DAYS


def retention_days(organization) -> int:
    """Days of history kept for this customer; 0 = keep."""
    from psa_ai.models import AIBusinessPolicy
    value = (AIBusinessPolicy.objects.filter(organization=organization)
             .values_list('history_retention_days', flat=True).first())
    return default_retention_days() if value is None else value


def cutoff_for(organization, now=None):
    days = retention_days(organization)
    return None if not days else (now or timezone.now()) - timedelta(days=days)


def purge_expired(now=None) -> dict:
    """Delete AI and automation history older than each customer's window.

    Kept regardless of age: AI suggestions awaiting approval and analysis
    jobs / RMM requests that are still open (they are still in use), routing
    decisions and alert → ticket links (see the module docstring)."""
    from core.models import Organization
    from psa_ai.models import AIBusinessPolicy, AIDraftDecision, AISuggestion, AnalysisJob, RMMRequest
    now = now or timezone.now()
    custom = dict(AIBusinessPolicy.objects.exclude(history_retention_days=None)
                  .values_list('organization_id', 'history_retention_days'))
    groups = {}
    default = default_retention_days()
    for org_id in Organization.objects.values_list('pk', flat=True):
        groups.setdefault(custom.get(org_id, default), []).append(org_id)
    deleted = {'suggestions': 0, 'analysis_jobs': 0, 'rmm_requests': 0, 'draft_decisions': 0}
    for days, org_ids in groups.items():
        if not days:
            continue
        cutoff = now - timedelta(days=days)
        with transaction.atomic():
            deleted['draft_decisions'] += AIDraftDecision.objects.filter(
                organization_id__in=org_ids, created_at__lt=cutoff).delete()[0]
            deleted['suggestions'] += AISuggestion.objects.filter(
                organization_id__in=org_ids, created_at__lt=cutoff).exclude(
                review_state='pending_review').delete()[1].get('psa_ai.AISuggestion', 0)
            deleted['analysis_jobs'] += AnalysisJob.objects.filter(
                organization_id__in=org_ids, created_at__lt=cutoff,
                status__in=AnalysisJob.TERMINAL).delete()[1].get('psa_ai.AnalysisJob', 0)
            deleted['rmm_requests'] += RMMRequest.objects.filter(
                organization_id__in=org_ids, created_at__lt=cutoff,
                status__in=RMMRequest.TERMINAL).delete()[1].get('psa_ai.RMMRequest', 0)
    return deleted


def purge_if_due(now=None):
    """Run purge_expired() if it hasn't run within PURGE_EVERY. Returns the
    counts, or None when it wasn't due."""
    from psa_ai.models import AIHistoryPurgeState
    now = now or timezone.now()
    state, _ = AIHistoryPurgeState.objects.get_or_create(pk=1)
    if state.last_run_at and now - state.last_run_at < PURGE_EVERY:
        return None
    # Claim the run first, so two schedulers racing purge once.
    claimed = AIHistoryPurgeState.objects.filter(pk=1, last_run_at=state.last_run_at).update(last_run_at=now)
    if not claimed:
        return None
    counts = purge_expired(now)
    AIHistoryPurgeState.objects.filter(pk=1).update(last_deleted=counts)
    return counts


# --- recording human decisions on AI drafts ------------------------------------

def record_draft_decision(ticket, user, body, marker='', *, comment=None, internal=False, refused=False):
    """Record what a technician did with an AI draft, if `body` came from one
    of this ticket's drafts. Returns the AIDraftDecision or None."""
    from psa_ai.models import AIDraftDecision as D
    from .drafts import match_draft
    found = match_draft(ticket, body, marker)
    if found is None:
        return None
    source, suggestion_id, job_id, index, unchanged = found
    if refused:
        decision = D.SEND_REFUSED
    elif internal:
        decision = D.KEPT_INTERNAL
    else:
        decision = D.SENT if unchanged else D.SENT_EDITED
    return D.objects.create(organization_id=ticket.organization_id, ticket=ticket, source=source,
                            suggestion_id=suggestion_id, job_id=job_id, draft_index=index, decision=decision,
                            comment=comment, actor=user if getattr(user, 'pk', None) else None)


# --- the timeline ----------------------------------------------------------------

def _who(user):
    if user is None:
        return ''
    return user.get_full_name() or user.username


def _excerpt(text):
    from .evidence import redact
    text = redact(str(text or ''), max_chars=EXCERPT_CHARS * 2).strip()
    return text if len(text) <= EXCERPT_CHARS else text[:EXCERPT_CHARS].rstrip() + '…'


def _prompt_label(value):
    from .prompt_versions import is_hashed
    if not value:
        return ''
    return value if is_hashed(value) else f'{value} (legacy, no content hash)'


def ai_text_allowed(organization) -> bool:
    """AI-written text is shown only while AI is on for this customer."""
    from core.ai_gate import ai_features_enabled
    from psa_ai.models import AIBusinessPolicy
    if not ai_features_enabled():
        return False
    return AIBusinessPolicy.objects.filter(organization=organization, analysis_enabled=True).exists()


def _entry(at, kind, title, *, ai=False, actor='', icon='fa-robot'):
    return {'at': at, 'kind': kind, 'title': title, 'ai': ai, 'actor': actor, 'icon': icon, 'facts': [],
            'runs': [], 'decisions': [], 'approval': '', 'approval_expires_at': None, 'outcome': '',
            'error_code': '', 'excerpt': '', 'note': '', 'link': ''}


def _decision_line(d):
    return {'text': d.get_decision_display(), 'by': _who(d.actor), 'at': d.created_at,
            'comment_id': d.comment_id}


SUGGESTION_TITLES = {'reply': 'AI reply draft', 'action': 'AI suggested action', 'triage': 'AI triage guidance'}


def _suggestions(ticket, cutoff, show_text):
    from psa_ai.models import AISuggestion
    qs = (AISuggestion.objects.filter(native_ticket=ticket)
          .select_related('requested_by', 'requested_review_by', 'reviewer')
          .prefetch_related('action_logs__actor', 'draft_decisions__actor'))
    if cutoff:
        qs = qs.filter(created_at__gte=cutoff)
    out = []
    for s in qs.order_by('-created_at')[:MAX_ENTRIES]:
        title = SUGGESTION_TITLES.get(s.kind, 'AI suggestion')
        if s.kind == 'action' and s.action_type:
            title += f': {s.action_type}'
        e = _entry(s.created_at, 'ai_suggestion', title, ai=True, actor=_who(s.requested_by))
        model = s.model_name + (f' {s.model_version}' if s.model_version else '')
        e['facts'] = [('Model', model or '—'), ('Prompt version', _prompt_label(s.prompt_version) or '—'),
                      ('State', s.get_review_state_display()), ('Risk', s.get_risk_level_display()),
                      ('Confidence', f'{s.confidence:.2f}')]
        if s.requested_review_at:
            e['decisions'].append({'text': 'Approval requested', 'by': _who(s.requested_review_by),
                                   'at': s.requested_review_at})
        if s.reviewed_at and s.review_state in ('approved', 'rejected'):
            word = {'approved': 'Approved' if s.kind == 'action' else 'Marked helpful',
                    'rejected': 'Rejected'}[s.review_state]
            e['decisions'].append({'text': word + (f' — "{s.reviewer_note[:200]}"' if s.reviewer_note else ''),
                                   'by': _who(s.reviewer), 'at': s.reviewed_at})
        for log in s.action_logs.all():
            e['decisions'].append({'text': 'Applied' if log.success else f'Apply failed: {log.error[:200]}',
                                   'by': _who(log.actor), 'at': log.applied_at})
        e['decisions'] += [_decision_line(d) for d in s.draft_decisions.all()]
        if s.kind == 'action':
            e['approval'] = ('Applying needs the "apply AI-suggested change" capability; a technician without it '
                             'requests approval and a reviewer with "review others" decides.')
            if s.review_state == 'pending_review':
                e['approval'] += ' Awaiting approval; this request has no expiry and waits for a reviewer.'
        elif s.kind == 'reply':
            e['approval'] = ('Never sent from the draft: only the technician\'s own Send publishes it, and a '
                             'public send needs the "send AI-assisted replies" capability.')
        if s.review_state in ('blocked', 'failed'):
            e['outcome'] = s.get_review_state_display()
        if show_text and s.review_state not in ('blocked', 'failed'):
            e['excerpt'] = _excerpt(s.suggested_body)
        out.append(e)
    return out


def _job_excerpt(job, runs):
    res = job.processor_result or {}
    for run in runs:
        r = run.result or {}
        if run.status == 'succeeded':
            text = r.get('summary') or next((c.get('text') for c in r.get('likely_causes') or [] if c.get('text')), '')
            if text:
                return text
    facts = res.get('facts') or []
    if facts and isinstance(facts[0], dict):
        return facts[0].get('statement', '')
    return ''


def _jobs(ticket, cutoff, show_text):
    from psa_ai.models import AnalysisJob
    qs = (AnalysisJob.objects.filter(ticket=ticket).select_related('actor', 'connection')
          .prefetch_related('runs__profile', 'draft_decisions__actor'))
    if cutoff:
        qs = qs.filter(created_at__gte=cutoff)
    out = []
    for job in qs.order_by('-created_at')[:MAX_ENTRIES]:
        runs = list(job.runs.all())
        title = 'Ticket analysis' if job.kind == job.KIND_ANALYZE else 'Model comparison'
        e = _entry(job.created_at, 'ai_analysis', f'{title} via {job.connection.name}', ai=True,
                   actor=_who(job.actor), icon='fa-microscope')
        e['facts'] = [('Protocol', job.get_protocol_display()), ('Status', job.get_status_display()),
                      ('Job expires', timezone.localtime(job.expires_at).strftime('%Y-%m-%d %H:%M'))]
        if job.processor_job_id:
            e['facts'].append(('Processor job', job.processor_job_id))
        for run in runs:
            e['runs'].append({
                'profile': run.profile.name,
                'model': run.resolved_model or f'{run.profile.provider}/{run.profile.model} (as configured now)',
                'prompt_version': _prompt_label(run.prompt_version) or 'not run',
                'status': run.get_status_display(), 'error': run.error[:200],
                'tokens': run.input_tokens + run.output_tokens,
                'cost_cents': run.actual_cost / 100 if run.actual_cost else 0,
            })
        e['error_code'] = job.processor_error_code
        if job.status in ('failed', 'unavailable', 'expired', 'partial'):
            e['outcome'] = (job.error or job.get_status_display())[:300]
        if job.protocol == job.PROTOCOL_REM0TE and job.processor_result:
            res = job.processor_result
            e['facts'].append(('Rem0te result', f'{len(res.get("facts") or [])} verified fact(s), '
                                                f'{len(res.get("unsupported_claims") or [])} unsupported claim(s), '
                                                f'{len(res.get("partial_failures") or [])} partial failure(s)'))
        e['approval'] = ('No approval step: the result is advisory and staff-only. Drafts go to the composer '
                         'only; nothing is sent, run or changed by the analysis.')
        e['decisions'] = [_decision_line(d) for d in job.draft_decisions.all()]
        if show_text:
            e['excerpt'] = _excerpt(_job_excerpt(job, runs))
        out.append(e)
    return out


RMM_TITLES = {'handoff': 'Handoff to RMM', 'diagnostic': 'Read-only diagnostic', 'fix_referral': 'Fix referral'}


def _rmm_requests(ticket, cutoff):
    from psa_ai.models import RMMRequest
    from .rmm_actions import EXPIRE_AFTER
    qs = RMMRequest.objects.filter(ticket=ticket).select_related('actor', 'connection')
    if cutoff:
        qs = qs.filter(created_at__gte=cutoff)
    out = []
    for req in qs.order_by('-created_at')[:MAX_ENTRIES]:
        rem0te = getattr(req.connection, 'provider_type', '') == 'rem0te'
        title = RMM_TITLES.get(req.kind, 'RMM request')
        if req.kind == RMMRequest.KIND_FIX and rem0te:
            title = 'Rem0te action proposal'
        detail = req.diagnostic_label or req.fix_title
        e = _entry(req.created_at, 'rmm_request', f'{title}{": " + detail if detail else ""}',
                   actor=_who(req.actor), icon='fa-server')
        e['facts'] = [('RMM', req.connection.name), ('Device', req.device_name or req.device_external_id),
                      ('Status', req.get_status_display())]
        if req.remote_status:
            e['facts'].append(('RMM status', req.remote_status))
        if req.fix_risk:
            e['facts'].append(('Risk', req.get_fix_risk_display()))
        if req.kind == RMMRequest.KIND_FIX:
            parts = [f'Approval happens in {req.connection.name}, by its approvers; ClientSt0r never approves '
                     'or runs anything.']
            if req.approvals_required:
                parts.append(f'{req.approvals_required} approval(s) required.')
            if req.customer_signoff:
                parts.append('Customer sign-off required.')
            e['approval'] = ' '.join(parts)
            e['approval_expires_at'] = req.approval_expires_at or (
                None if req.is_terminal else req.created_at + EXPIRE_AFTER['fix_referral'])
            if req.approval_url and req.status == 'received':
                e['link'] = req.approval_url
        elif not req.is_terminal:
            e['approval_expires_at'] = req.created_at + EXPIRE_AFTER.get(req.kind, timedelta(hours=1))
        outcome = []
        if req.remote_outcome:
            outcome.append(f'Outcome: {req.remote_outcome}')
        if req.observed:
            outcome.append('Observed: ' + ', '.join(f'{k}={v}' for k, v in req.observed.items()))
        elif req.status_note:
            outcome.append(req.status_note[:300])
        if req.kind == RMMRequest.KIND_DIAGNOSTIC and req.result_bytes:
            outcome.append(f'Result: {req.result_bytes} bytes (in the RMM panel)')
        if req.error:
            outcome.append(req.error[:300])
        e['outcome'] = ' · '.join(outcome)
        out.append(e)
    return out


def _alerts(ticket, cutoff):
    from psa_ai.models import Rem0teAlertTicket
    qs = Rem0teAlertTicket.objects.filter(ticket=ticket).select_related('connection')
    if cutoff:
        qs = qs.filter(created_at__gte=cutoff)
    out = []
    for a in qs.order_by('-created_at')[:MAX_ENTRIES]:
        e = _entry(a.created_at, 'alert', f'Opened from a {a.connection.name} alert: {a.title}'[:300],
                   icon='fa-bell')
        e['facts'] = [('Computer', a.computer_name or a.rem0te_endpoint_id or '—'), ('Kind', a.kind or '—'),
                      ('Severity', a.severity or '—'), ('Alert state', a.state or '—'),
                      ('Link back', a.get_link_status_display())]
        if a.resolved_at:
            e['outcome'] = f'Alert resolved {timezone.localtime(a.resolved_at):%Y-%m-%d %H:%M}'
        e['note'] = 'Opening the ticket started nothing on the computer.'
        out.append(e)
    return out


def _routing(ticket, cutoff):
    from psa.routing.models import RoutingDecision
    qs = (RoutingDecision.objects.filter(ticket=ticket)
          .select_related('rule_version', 'previous_assignee', 'new_assignee', 'previous_queue', 'new_queue',
                          'decided_by'))
    if cutoff:
        qs = qs.filter(created_at__gte=cutoff)
    out = []
    for d in qs.order_by('-created_at')[:MAX_ENTRIES]:
        e = _entry(d.created_at, 'routing', f'Routing: {d.get_status_display()} ({d.get_trigger_display()})',
                   icon='fa-route')
        prev = (_who(d.previous_assignee) or 'unassigned') + (f' ({d.previous_queue.name})' if d.previous_queue else '')
        new = (_who(d.new_assignee) or 'unassigned') + (f' ({d.new_queue.name})' if d.new_queue else '')
        e['facts'] = [('Mode', d.get_mode_display() or '—'),
                      ('Rule', f'{d.rule_version.name} v{d.rule_version.number}' if d.rule_version else '—'),
                      ('Assignment', f'{prev} → {new}' + (f' · team {d.new_team}' if d.new_team else ''))]
        if d.decided_by_id:
            e['decisions'].append({'text': d.get_status_display(), 'by': _who(d.decided_by), 'at': d.decided_at})
        if d.status == 'suggested':
            e['approval'] = 'Suggestion only: a dispatcher accepts or dismisses it in the Routing panel.'
        e['outcome'] = (d.reason or '')[:300]
        e['note'] = ROUTING_ASSURANCE
        out.append(e)
    return out


def build(ticket, user) -> dict:
    """The timeline for `user` on `ticket`. {'show': False} for anyone who is
    not an MSP technician."""
    from psa.visibility import is_msp_staff
    if ticket is None or not is_msp_staff(user):
        return {'show': False}
    from tech_access.resolver import has_any_assignment
    if not has_any_assignment(user, ticket.organization):
        # PSA lets MSP staff open every ticket; this history, like the RMM
        # panel, needs live technician access at the ticket's customer.
        return {'show': False}
    from psa_ai.permissions import has_capability
    ai_visible = has_capability(user, ticket.organization, 'view_output', ticket=ticket)
    show_text = ai_visible and ai_text_allowed(ticket.organization)
    cutoff = cutoff_for(ticket.organization)
    entries = []
    if ai_visible:
        entries += _suggestions(ticket, cutoff, show_text) + _jobs(ticket, cutoff, show_text)
    entries += _rmm_requests(ticket, cutoff) + _alerts(ticket, cutoff) + _routing(ticket, cutoff)
    entries.sort(key=lambda e: e['at'], reverse=True)
    entries = entries[:MAX_ENTRIES]
    entries.reverse()  # chronological, oldest first
    for e in entries:
        e['decisions'].sort(key=lambda d: d['at'] or e['at'])
    return {
        'show': bool(entries),
        'entries': entries,
        'ai_visible': ai_visible,
        'ai_text': show_text,
        'retention_days': retention_days(ticket.organization),
        'ticket': ticket,
    }
